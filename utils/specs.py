# Common property docstring lines
PROPS = {
    'pbc_selection': '* **pbc_selection** (*str*) - (None) Atom selection (VMD syntax) of atoms under Periodic Boundary Conditions (e.g. solvent, ions, membrane lipids), which are excluded from the analysis. Use \'auto\' to guess them. If not set, the value in the inputs file is used, or \'auto\' by default.',
    'cg_selection': '* **cg_selection** (*str*) - (None) Atom selection (VMD syntax) of Coarse Grained beads. Use \'auto\' to guess them. If not set, the value in the inputs file is used, or none by default.',
    'interactions': '* **interactions** (*list*) - (None) List of interactions to be analyzed. Each interaction is a dictionary with the fields name, agent_1, selection_1, agent_2, selection_2 and optionally distance_cutoff (Å). Selections are in VMD syntax. If not set, interactions in the inputs file are used.',
    'md_type': '* **md_type** (*str*) - (None) Type of molecular dynamics. If not set, the value in the inputs file is used, or \'trajectory\' by default. Values: trajectory (Frames are consecutive in time), ensemble (Frames are not related in time).',
    'framestep': '* **framestep** (*float*) - (None) Time between consecutive frames in nanoseconds (ns). If not set, the value in the inputs file is used.',
    'pca_fit_selection': '* **pca_fit_selection** (*str*) - (None) Atom selection (VMD syntax) for the fitting before the PCA. If not set, the workflow default is used: protein and nucleic acid backbone.',
    'pca_analysis_selection': '* **pca_analysis_selection** (*str*) - (None) Atom selection (VMD syntax) for the PCA. If not set, the workflow default is used: protein and nucleic acid backbone.',
    'energies_engine': '* **energies_engine** (*str*) - ("cmip") Engine used to calculate the energies. Values: cmip (Poisson-Boltzmann electrostatics on a grid using CMIP), gridfree (Coulomb with a sigmoidal distance-dependent dielectric and CMIP van der Waals parameters summed over atom pairs. Much faster).',
}

